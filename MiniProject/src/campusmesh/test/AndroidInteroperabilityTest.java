package campusmesh.test;

import campusmesh.contact.ContactManager;
import campusmesh.discovery.DiscoveredPeer;
import campusmesh.discovery.DiscoveryManager;
import campusmesh.discovery.PeerRegistry;
import campusmesh.model.Message;
import campusmesh.model.Peer;
import campusmesh.model.Priority;
import campusmesh.networking.TCPManager;

import java.io.DataInputStream;
import java.io.DataOutputStream;
import java.net.ServerSocket;
import java.net.Socket;
import java.nio.charset.StandardCharsets;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;

/**
 * Automated verification test harness for Phase 2:
 * Validates cross-platform wire compatibility and interoperability between
 * the Android client implementation and the existing Java desktop nodes.
 */
public class AndroidInteroperabilityTest {

    private static int testsRun = 0;
    private static int testsPassed = 0;

    public static void main(String[] args) {
        System.out.println("==================================================");
        System.out.println("  CAMPUSMESH ANDROID INTEROPERABILITY TEST SUITE  ");
        System.out.println("==================================================\n");

        runTest("Android <-> Java JSON Wire Compatibility", AndroidInteroperabilityTest::testJsonWireCompatibility);
        runTest("Android -> Java 4-byte Binary TCP Framing", AndroidInteroperabilityTest::testAndroidToJavaTcpFraming);
        runTest("Java -> Android Simulated TCP Delivery", AndroidInteroperabilityTest::testJavaToAndroidTcpDelivery);
        runTest("Android Peer Metadata & Registry Auto-Sync", AndroidInteroperabilityTest::testAndroidPeerMetadataAndRegistry);

        System.out.println("\n==================================================");
        System.out.printf("ANDROID INTEROP RESULTS: %d / %d PASSED%n", testsPassed, testsRun);
        System.out.println("==================================================");

        if (testsPassed != testsRun) {
            System.err.println("Some Android interoperability tests failed!");
            System.exit(1);
        } else {
            System.out.println("ALL ANDROID INTEROPERABILITY TESTS PASSED!");
        }
    }

    private static void runTest(String testName, Runnable testMethod) {
        testsRun++;
        try {
            testMethod.run();
            testsPassed++;
            System.out.println("  [PASS] " + testName);
        } catch (Throwable t) {
            System.err.println("  [FAIL] " + testName + " - " + t.getMessage());
            t.printStackTrace(System.err);
        }
    }

    private static void assertTrue(boolean condition, String message) {
        if (!condition) {
            throw new AssertionError("Assertion failed: " + message);
        }
    }

    private static void assertEquals(Object expected, Object actual, String message) {
        if (expected == null && actual == null) return;
        if (expected != null && expected.equals(actual)) return;
        throw new AssertionError(String.format("%s (expected: '%s', actual: '%s')", message, expected, actual));
    }

    // 1. Android JSON serialization <-> Java deserialization test
    private static void testJsonWireCompatibility() {
        // Wire JSON as generated by Android Message.kt
        String androidGeneratedJson = "{"
                + "\"messageId\":\"AND_MSG_99\","
                + "\"sourceId\":\"AND_PHONE\","
                + "\"destinationId\":\"LAPTOP_A\","
                + "\"createdAt\":\"2026-10-17T16:00:00Z\","
                + "\"expiresAt\":\"2026-10-17T17:00:00Z\","
                + "\"priority\":\"HIGH\","
                + "\"copyTokens\":4,"
                + "\"payload\":\"Android offline mesh packet with \\\"escaped\\\" quotes and \\n newline\""
                + "}";

        Message parsed = Message.fromJson(androidGeneratedJson);
        assertEquals("AND_MSG_99", parsed.getMessageId(), "Message ID must match");
        assertEquals("AND_PHONE", parsed.getSourceId(), "Source ID must match");
        assertEquals("LAPTOP_A", parsed.getDestinationId(), "Destination ID must match");
        assertEquals(Priority.HIGH, parsed.getPriority(), "Priority must match HIGH");
        assertEquals(4, parsed.getCopyTokens(), "Copy tokens must match 4");
        assertEquals("Android offline mesh packet with \"escaped\" quotes and \n newline", parsed.getPayload(), "Payload must correctly unescape quotes and newlines");

        // Reverse test: Java message toJson() -> verify field presence
        String javaJson = parsed.toJson();
        assertTrue(javaJson.contains("\"messageId\":\"AND_MSG_99\""), "Java JSON must contain messageId");
        assertTrue(javaJson.contains("\"priority\":\"HIGH\""), "Java JSON must contain priority");
    }

    // 2. Android 4-byte big-endian framing to Java TCPManager test
    private static void testAndroidToJavaTcpFraming() {
        int testPort = 5988;
        CountDownLatch latch = new CountDownLatch(1);
        final Message[] receivedHolder = new Message[1];

        try (TCPManager javaServer = new TCPManager()) {
            javaServer.startServer(testPort, (msg, socket) -> {
                receivedHolder[0] = msg;
                latch.countDown();
            });

            Thread.sleep(100);

            // Emulate Android client socket writing standard 4-byte prefix + UTF-8 payload
            try (Socket androidSocket = new Socket("127.0.0.1", testPort)) {
                String payload = "{\"messageId\":\"AND_TO_JAVA_1\",\"sourceId\":\"ANDROID_CLIENT\",\"destinationId\":\"JAVA_SERVER\",\"createdAt\":\"2026-10-17T16:00:00Z\",\"expiresAt\":\"2026-10-17T18:00:00Z\",\"priority\":\"MEDIUM\",\"copyTokens\":2,\"payload\":\"Hello from Android\"}";
                byte[] rawBytes = payload.getBytes(StandardCharsets.UTF_8);

                DataOutputStream dos = new DataOutputStream(androidSocket.getOutputStream());
                dos.writeInt(rawBytes.length); // 4-byte big-endian length
                dos.write(rawBytes);
                dos.flush();

                boolean received = latch.await(2, TimeUnit.SECONDS);
                assertTrue(received, "Java server must receive Android-framed message within 2s");
                assertEquals("AND_TO_JAVA_1", receivedHolder[0].getMessageId(), "Received ID must match");
                assertEquals("ANDROID_CLIENT", receivedHolder[0].getSourceId(), "Received source must match");
                assertEquals("Hello from Android", receivedHolder[0].getPayload(), "Received payload must match");
            }
        } catch (Exception e) {
            throw new RuntimeException("Android to Java TCP framing test failed: " + e.getMessage(), e);
        }
    }

    // 3. Java TCPManager sending to simulated Android TCP listener
    private static void testJavaToAndroidTcpDelivery() {
        int androidPort = 5989;
        CountDownLatch latch = new CountDownLatch(1);
        final String[] androidReceivedJson = new String[1];

        // Emulate Android TCP server loop
        try (ServerSocket androidServer = new ServerSocket(androidPort)) {
            Thread androidListener = new Thread(() -> {
                try (Socket client = androidServer.accept();
                     DataInputStream dis = new DataInputStream(client.getInputStream())) {
                    int len = dis.readInt();
                    byte[] buf = new byte[len];
                    dis.readFully(buf);
                    androidReceivedJson[0] = new String(buf, StandardCharsets.UTF_8);
                    latch.countDown();
                } catch (Exception ignored) {}
            });
            androidListener.setDaemon(true);
            androidListener.start();

            Thread.sleep(100);

            // Java TCPManager sends message to Android
            try (TCPManager javaClient = new TCPManager();
                 Socket s = javaClient.connectToPeer("127.0.0.1", androidPort)) {
                Message msg = new Message("JAVA_TO_AND_1", "LAPTOP_NODE", "ANDROID_PHONE",
                        Priority.HIGH, "Emergency Campus Announcement", 120, 2);
                javaClient.sendMessage(s, msg);

                boolean ok = latch.await(2, TimeUnit.SECONDS);
                assertTrue(ok, "Android receiver must capture Java length-prefixed frame");
                assertTrue(androidReceivedJson[0].contains("\"messageId\":\"JAVA_TO_AND_1\""), "Android must receive messageId");
                assertTrue(androidReceivedJson[0].contains("Emergency Campus Announcement"), "Android must receive payload");
            }
        } catch (Exception e) {
            throw new RuntimeException("Java to Android TCP delivery failed: " + e.getMessage(), e);
        }
    }

    // 4. Android Peer metadata and registry auto-sync test
    private static void testAndroidPeerMetadataAndRegistry() {
        Peer localLaptop = new Peer("LAPTOP_MASTER", "127.0.0.1", 5001);
        ContactManager cm = new ContactManager(localLaptop);

        try (DiscoveryManager dm = new DiscoveryManager(localLaptop, cm)) {
            // Simulated observation from Android device
            DiscoveredPeer androidPeer = new DiscoveredPeer(
                    "AND_GALAXY_S23",
                    "Bhumika's Android",
                    "ANDROID",
                    "192.168.1.155",
                    5005
            );
            androidPeer.addTransport("WIFI");
            androidPeer.addAttribute("caps", "WIFI,BLE,DTN");

            boolean registered = dm.getRegistry().registerOrUpdate(androidPeer);
            assertTrue(registered, "Android peer should register successfully");

            // Verify metadata
            DiscoveredPeer retrieved = dm.getRegistry().getPeer("AND_GALAXY_S23");
            assertEquals("ANDROID", retrieved.getPlatform(), "Platform must be ANDROID");
            assertEquals(5005, retrieved.getPort(), "Port must match Android port 5005");
            assertEquals("192.168.1.155", retrieved.getIpAddress(), "IP address must match");

            // Verify automatic ContactManager encounter triggering
            assertTrue(cm.isInContact("AND_GALAXY_S23"), "ContactManager must have an active encounter with the Android device");
        }
    }
}
