package campusmesh.test;

import campusmesh.contact.ContactManager;
import campusmesh.discovery.DiscoveredPeer;
import campusmesh.discovery.DiscoveryManager;
import campusmesh.model.Message;
import campusmesh.model.Peer;
import campusmesh.model.Priority;
import campusmesh.networking.TCPManager;

import java.io.DataInputStream;
import java.io.DataOutputStream;
import java.net.ServerSocket;
import java.net.Socket;
import java.nio.charset.StandardCharsets;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;

/**
 * Automated verification test harness for Phase 3:
 * Validates cross-platform wire compatibility and interoperability between
 * the iOS Swift client implementation and the existing Java desktop nodes.
 */
public class IOSInteroperabilityTest {

    private static int testsRun = 0;
    private static int testsPassed = 0;

    public static void main(String[] args) {
        System.out.println("==================================================");
        System.out.println("    CAMPUSMESH IOS INTEROPERABILITY TEST SUITE    ");
        System.out.println("==================================================\n");

        runTest("iOS <-> Java JSON Wire Compatibility", IOSInteroperabilityTest::testJsonWireCompatibility);
        runTest("iOS -> Java 4-byte Binary TCP Framing", IOSInteroperabilityTest::testIosToJavaTcpFraming);
        runTest("Java -> iOS Simulated TCP Delivery", IOSInteroperabilityTest::testJavaToIosTcpDelivery);
        runTest("iOS Peer Metadata & Registry Auto-Sync", IOSInteroperabilityTest::testIosPeerDiscoveryAndRegistrySync);

        System.out.println("\n==================================================");
        System.out.printf("IOS INTEROP RESULTS: %d / %d PASSED%n", testsPassed, testsRun);
        System.out.println("==================================================");

        if (testsPassed != testsRun) {
            System.err.println("Some iOS interoperability tests failed!");
            System.exit(1);
        } else {
            System.out.println("ALL IOS INTEROPERABILITY TESTS PASSED!");
        }
    }

    private static void runTest(String testName, Runnable testMethod) {
        testsRun++;
        try {
            testMethod.run();
            testsPassed++;
            System.out.println("  [PASS] " + testName);
        } catch (Throwable t) {
            System.err.println("  [FAIL] " + testName + " - " + t.getMessage());
            t.printStackTrace(System.err);
        }
    }

    private static void assertTrue(boolean condition, String message) {
        if (!condition) {
            throw new AssertionError("Assertion failed: " + message);
        }
    }

    private static void assertEquals(Object expected, Object actual, String message) {
        if (expected == null && actual == null) return;
        if (expected != null && expected.equals(actual)) return;
        throw new AssertionError(String.format("%s (expected: '%s', actual: '%s')", message, expected, actual));
    }

    // 1. iOS Swift JSON serialization <-> Java deserialization test
    private static void testJsonWireCompatibility() {
        // Wire JSON as generated by iOS Message.swift
        String iosGeneratedJson = "{"
                + "\"messageId\":\"IOS_MSG_77\","
                + "\"sourceId\":\"IPHONE_15_PRO\","
                + "\"destinationId\":\"WINDOWS_HOST\","
                + "\"createdAt\":\"2026-10-17T16:15:00Z\","
                + "\"expiresAt\":\"2026-10-17T18:15:00Z\","
                + "\"priority\":\"HIGH\","
                + "\"copyTokens\":6,"
                + "\"payload\":\"Apple Network.framework DTN frame with special chars \\\"quotes\\\" and line\\nbreak\""
                + "}";

        Message parsed = Message.fromJson(iosGeneratedJson);
        assertEquals("IOS_MSG_77", parsed.getMessageId(), "Message ID must match");
        assertEquals("IPHONE_15_PRO", parsed.getSourceId(), "Source ID must match");
        assertEquals("WINDOWS_HOST", parsed.getDestinationId(), "Destination ID must match");
        assertEquals(Priority.HIGH, parsed.getPriority(), "Priority must match HIGH");
        assertEquals(6, parsed.getCopyTokens(), "Copy tokens must match 6");
        assertEquals("Apple Network.framework DTN frame with special chars \"quotes\" and line\nbreak", parsed.getPayload(), "Payload unescaping must match");

        // Reverse check: verify Java output is parseable by iOS Swift contract
        String javaJson = parsed.toJson();
        assertTrue(javaJson.contains("\"messageId\":\"IOS_MSG_77\""), "Java JSON must contain messageId");
        assertTrue(javaJson.contains("\"priority\":\"HIGH\""), "Java JSON must contain priority");
        assertTrue(javaJson.contains("\"copyTokens\":6"), "Java JSON must contain copyTokens");
    }

    // 2. iOS NWConnection 4-byte framing to Java TCPManager test
    private static void testIosToJavaTcpFraming() {
        int testPort = 5992;
        CountDownLatch latch = new CountDownLatch(1);
        final Message[] receivedHolder = new Message[1];

        try (TCPManager javaServer = new TCPManager()) {
            javaServer.startServer(testPort, (msg, socket) -> {
                receivedHolder[0] = msg;
                latch.countDown();
            });

            Thread.sleep(100);

            // Emulate iOS client NWConnection writing 4-byte big-endian prefix + UTF-8 payload
            try (Socket iosSocket = new Socket("127.0.0.1", testPort)) {
                String payload = "{\"messageId\":\"IOS_TO_JAVA_1\",\"sourceId\":\"IPHONE_AIR\",\"destinationId\":\"JAVA_DESKTOP\",\"createdAt\":\"2026-10-17T16:20:00Z\",\"expiresAt\":\"2026-10-17T18:20:00Z\",\"priority\":\"LOW\",\"copyTokens\":1,\"payload\":\"Hello from iOS Network.framework!\"}";
                byte[] rawBytes = payload.getBytes(StandardCharsets.UTF_8);

                DataOutputStream dos = new DataOutputStream(iosSocket.getOutputStream());
                dos.writeInt(rawBytes.length); // 4-byte big-endian UInt32 length
                dos.write(rawBytes);
                dos.flush();

                boolean received = latch.await(2, TimeUnit.SECONDS);
                assertTrue(received, "Java server must receive iOS-framed message within 2s");
                assertEquals("IOS_TO_JAVA_1", receivedHolder[0].getMessageId(), "Received ID must match");
                assertEquals("IPHONE_AIR", receivedHolder[0].getSourceId(), "Received source must match");
                assertEquals("Hello from iOS Network.framework!", receivedHolder[0].getPayload(), "Received payload must match");
            }
        } catch (Exception e) {
            throw new RuntimeException("iOS to Java TCP framing test failed: " + e.getMessage(), e);
        }
    }

    // 3. Java TCPManager sending to simulated iOS NWListener
    private static void testJavaToIosTcpDelivery() {
        int iosPort = 5993;
        CountDownLatch latch = new CountDownLatch(1);
        final String[] iosReceivedJson = new String[1];

        // Emulate iOS NWListener TCP server socket
        try (ServerSocket iosServer = new ServerSocket(iosPort)) {
            Thread iosListener = new Thread(() -> {
                try (Socket client = iosServer.accept();
                     DataInputStream dis = new DataInputStream(client.getInputStream())) {
                    int len = dis.readInt();
                    byte[] buf = new byte[len];
                    dis.readFully(buf);
                    iosReceivedJson[0] = new String(buf, StandardCharsets.UTF_8);
                    latch.countDown();
                } catch (Exception ignored) {}
            });
            iosListener.setDaemon(true);
            iosListener.start();

            Thread.sleep(100);

            // Java TCPManager sends message to iOS listener
            try (TCPManager javaClient = new TCPManager();
                 Socket s = javaClient.connectToPeer("127.0.0.1", iosPort)) {
                Message msg = new Message("JAVA_TO_IOS_99", "JAVA_HOST", "IPHONE_NODE",
                        Priority.HIGH, "Direct delivery to iPhone NWListener", 120, 2);
                javaClient.sendMessage(s, msg);

                boolean ok = latch.await(2, TimeUnit.SECONDS);
                assertTrue(ok, "iOS receiver must capture Java length-prefixed frame");
                assertTrue(iosReceivedJson[0].contains("\"messageId\":\"JAVA_TO_IOS_99\""), "iOS must receive messageId");
                assertTrue(iosReceivedJson[0].contains("Direct delivery to iPhone NWListener"), "iOS must receive payload");
            }
        } catch (Exception e) {
            throw new RuntimeException("Java to iOS TCP delivery failed: " + e.getMessage(), e);
        }
    }

    // 4. iOS Bonjour/UDP peer metadata and automatic registry / contact synchronization
    private static void testIosPeerDiscoveryAndRegistrySync() {
        Peer localLaptop = new Peer("LAPTOP_UBUNTU", "127.0.0.1", 5001);
        ContactManager cm = new ContactManager(localLaptop);

        try (DiscoveryManager dm = new DiscoveryManager(localLaptop, cm)) {
            // Simulated observation from iOS device
            DiscoveredPeer iosPeer = new DiscoveredPeer(
                    "IPHONE_15_PRO_MAX",
                    "iPhone 15 Pro",
                    "IOS",
                    "192.168.1.140",
                    5000
            );
            iosPeer.addTransport("WIFI");
            iosPeer.addAttribute("caps", "WIFI,BLE,DTN");

            boolean registered = dm.getRegistry().registerOrUpdate(iosPeer);
            assertTrue(registered, "iOS peer should register successfully");

            // Verify metadata
            DiscoveredPeer retrieved = dm.getRegistry().getPeer("IPHONE_15_PRO_MAX");
            assertTrue(retrieved != null, "iOS Peer must be found in registry");
            assertEquals("IOS", retrieved.getPlatform(), "Platform must be recorded as IOS");
            assertEquals("iPhone 15 Pro", retrieved.getDisplayName(), "Display name must match");
            assertEquals(5000, retrieved.getPort(), "Port must match 5000");
            assertEquals("192.168.1.140", retrieved.getIpAddress(), "IP address must match");
            assertTrue(retrieved.getSupportedTransports().contains("WIFI"), "Transport must include WIFI");

            // Bridge to legacy Peer model used by existing DTN routing algorithms
            Peer legacyPeer = retrieved.toPeer();
            assertEquals("IPHONE_15_PRO_MAX", legacyPeer.getPeerId(), "Legacy Peer ID must match");
            assertEquals("192.168.1.140", legacyPeer.getIpAddress(), "Legacy Peer IP must match");
            assertEquals(5000, legacyPeer.getPort(), "Legacy Peer port must match");

            // Verify automatic ContactManager encounter triggering
            assertTrue(cm.isInContact("IPHONE_15_PRO_MAX"), "ContactManager must have an active encounter with the iOS device");
        }
    }
}
